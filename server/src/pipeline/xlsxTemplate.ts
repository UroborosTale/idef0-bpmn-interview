/** Книга Excel с образцом и инструкцией. */
export function stepsTemplateXlsx(): Buffer {
  const wb = XLSX.utils.book_new();
  const steps = XLSX.utils.aoa_to_sheet([HEADER, ...ROWS]);
  steps["!cols"] = [{ wch: 5 }, { wch: 36 }, { wch: 12 }, { wch: 16 }, { wch: 18 }, { wch: 12 }, { wch: 14 }, { wch: 20 }, { wch: 10 }, { wch: 28 }];
  XLSX.utils.book_append_sheet(wb, steps, "Шаги");
  const help = XLSX.utils.aoa_to_sheet(HELP);
  help["!cols"] = [{ wch: 16 }, { wch: 110 }];
  XLSX.utils.book_append_sheet(wb, help, "Как заполнять");
  return XLSX.write(wb, { type: "buffer", bookType: "xlsx" }) as Buffer;
}
