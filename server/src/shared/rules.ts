/**
 * Правила моделирования по Соглашению: эвристики разбора названий. Это подсказки автору, а не грамматический
 * разбор, поэтому проверки, которые на них опираются, выдают предупреждения.
 */

const words = (name: string) => name.toLowerCase().match(/[\p{L}-]+/gu) ?? [];

// Причастие или глагол прошедшего времени: «заявка получена», «реестр актуализирован», «сотрудник принял решение».
const PARTICIPLE = /(?:[аяеё]н|ён)(?:а|о|ы)?$/u; // создан, получена, согласованы
const SHORT_PARTICIPLE = /(?:ыт|ут|ит|ят)(?:а|о|ы)?$/u; // закрыт, принят, открыта
const PAST_VERB = /[аяиеыу]л(?:а|и)?(?:ся|сь)?$/u; // получил, поступила, согласовали

/** Название события сформулировано как факт («Получена заявка»), а не как существительное или действие. */
export function looksLikeFact(name: string): boolean {
  return words(name).some((w) => w.length > 4 && (PARTICIPLE.test(w) || SHORT_PARTICIPLE.test(w) || PAST_VERB.test(w)));
}

// Отглагольные существительные без характерного суффикса
const BARE_VERBAL_NOUNS = new Set(["анализ", "контроль", "учёт", "учет", "подбор", "отбор", "расчёт", "расчет", "выбор", "сбор", "вывод", "ввод", "приём", "прием", "запуск", "выпуск", "заказ", "обмен", "обзор", "поиск", "аудит", "надзор", "найм", "уход", "обход"]);

/** Отглагольное существительное («актуализация реестра», «проверка заявки») — допустимое название блока IDEF0. */
export function hasVerbalNoun(name: string): boolean {
  return words(name).some((w) => (/(?:ние|тие|ция|ка|ство|тка|ча|инг)$/u.test(w) && w.length > 4) || BARE_VERBAL_NOUNS.has(w));
}

/** Код функции по Соглашению в произвольном тексте (поставщик или потребитель продукта). */
export const FUNCTION_CODE = /(?<![\p{L}\d])[ABCАВС]\d{3}\.\d{2}\.\d{2}(?![\d])/gu;

/** Латинская запись кода: кириллические А, В, С приводятся к латинским. */
export function normalizeCode(code: string): string {
  return code.replace(/А/g, "A").replace(/В/g, "B").replace(/С/g, "C");
}

/** Нормализованное название блока для поиска повторов. */
export const blockKey = (name: string) => name.toLowerCase().replace(/\s+/g, " ").trim();
